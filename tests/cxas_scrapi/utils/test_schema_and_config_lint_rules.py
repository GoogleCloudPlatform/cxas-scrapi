def test_a018_validates_tool_and_toolset_env_vars(tmp_path: Path) -> None:
    a018 = ToolAndToolsetEnvVars()
    app_dir = tmp_path / "app"
    ts_dir = app_dir / "toolsets" / "find_customer"
    ts_dir.mkdir(parents=True)
    mcp_dir = app_dir / "toolsets" / "orders_mcp"
    mcp_dir.mkdir(parents=True)
    oa_dir = app_dir / "tools" / "orders_api"
    (oa_dir / "open_api_tool").mkdir(parents=True)

    app_json = app_dir / "app.json"
    app_json.write_text(json.dumps({"displayName": "MyApp"}))
    (ts_dir / "find_customer.json").write_text(
        json.dumps(
            {
                "displayName": "Find Customer",
                "connectorToolset": {
                    "connection": "$env_var",
                    "connectorActions": [{"connectionActionId": "GetAccount"}],
                },
            }
        )
    )
    (mcp_dir / "orders_mcp.json").write_text(
        json.dumps(
            {
                "displayName": "Orders MCP",
                "mcpToolset": {"serverAddress": "$env_var"},
            }
        )
    )
    (oa_dir / "open_api_tool" / "open_api_schema.yaml").write_text(
        "openapi: 3.0.0\nservers:\n  - url: $env_var\npaths: {}\n"
    )
    (oa_dir / "orders_api.json").write_text(
        json.dumps(
            {
                "displayName": "Orders API",
                "openApiTool": {
                    "openApiSchema": (
                        "tools/orders_api/open_api_tool/open_api_schema.yaml"
                    )
                },
            }
        )
    )

    # Without environment.json or --env-file, deferred push-time overrides pass
    ctx = LintContext(
        project_root=tmp_path, app_dir=app_dir, evals_dir=tmp_path
    )
    assert a018.check(app_json, app_json.read_text(), ctx) == []

    # Missing entries in environment.json trigger A018
    (app_dir / "environment.json").write_text(
        json.dumps({"toolsets": {}, "tools": {}})
    )
    results = a018.check(app_json, app_json.read_text(), ctx)
    assert len(results) == 3
    assert all("missing from environment.json" in r.message for r in results)

    # Invalid formats trigger A018
    (app_dir / "environment.json").write_text(
        json.dumps(
            {
                "toolsets": {
                    "find_customer": {
                        "connectorToolset": {"connection": "short-name"}
                    },
                    "orders_mcp": {"mcpToolset": {"serverAddress": "bad-url"}},
                },
                "tools": {
                    "orders_api": {"openApiTool": {"url": "not-a-url"}},
                },
            }
        )
    )
    results_bad = a018.check(app_json, app_json.read_text(), ctx)
    assert len(results_bad) == 3
    assert all("has invalid value" in r.message for r in results_bad)

    # Valid --env-file passes cleanly
    valid_env = tmp_path / "env.uat.json"
    valid_env.write_text(
        json.dumps(
            {
                "toolsets": {
                    "find_customer": {
                        "connectorToolset": {
                            "connection": (
                                "projects/uat-proj/locations/us-central1/"
                                "connections/cymbal-uat"
                            )
                        }
                    },
                    "Orders MCP": {
                        "mcpToolset": {
                            "serverAddress": "https://mcp-uat.example.com/mcp/"
                        }
                    },
                },
                "tools": {
                    "orders_api": {
                        "openApiTool": {"url": "https://api-uat.example.com"}
                    }
                },
            }
        )
    )
    ctx_ext = LintContext(
        project_root=tmp_path,
        app_dir=app_dir,
        evals_dir=tmp_path,
        env_file=valid_env,
    )
    assert a018.check(app_json, app_json.read_text(), ctx_ext) == []


def test_a019_rejects_composite_models_on_agents_but_allows_app_and_standard(
    tmp_path: Path,
) -> None:
    a019 = AgentCompositeModelPlacement()
    ctx = LintContext(
        project_root=tmp_path, app_dir=tmp_path, evals_dir=tmp_path
    )

    # Allowed at app level
    app_json = tmp_path / "app.json"
    app_json.write_text(
        json.dumps(
            {
                "name": "voice_app",
                "displayName": "Voice App",
                "rootAgent": "root_agent",
                "modelSettings": {"model": "gemini-composite-v2"},
            }
        ),
        encoding="utf-8",
    )
    assert a019.check(app_json, app_json.read_text(), ctx) == []

    # Allowed non-composite override on agent
    std_agent = tmp_path / "agents" / "billing_agent" / "billing_agent.json"
    std_agent.parent.mkdir(parents=True)
    (std_agent.parent / "instruction.txt").write_text(
        "<role>Billing</role>\n<persona>Helpful</persona>\n"
        "<constraints>Today is {{current_date}}.</constraints>\n"
        "<taskflow>Help</taskflow>\n",
        encoding="utf-8",
    )
    std_agent.write_text(
        json.dumps(
            {
                "displayName": "billing_agent",
                "instruction": "agents/billing_agent/instruction.txt",
                "modelSettings": {"model": "gemini-2.5-flash"},
            }
        ),
        encoding="utf-8",
    )
    assert a019.check(std_agent, std_agent.read_text(), ctx) == []

    # Rejected on root agent (.yaml), sub-agent (.json), and sub-agent (.yml)
    root_yaml = tmp_path / "agents" / "root_agent" / "root_agent.yaml"
    root_yaml.parent.mkdir(parents=True)
    (root_yaml.parent / "instruction.txt").write_text(
        "<role>Root</role>\n<persona>Warm</persona>\n"
        "<constraints>Today is {{current_date}}.</constraints>\n"
        "<taskflow>Route to {@AGENT: billing_agent}, {@AGENT: sub_agent}, "
        "{@AGENT: yml_agent}, or {@AGENT: remote_df_sub}.</taskflow>\n",
        encoding="utf-8",
    )
    root_yaml.write_text(
        "displayName: root_agent\n"
        "instruction: agents/root_agent/instruction.txt\n"
        "tools:\n"
        "  - end_session\n"
        "childAgents:\n"
        "  - billing_agent\n"
        "  - sub_agent\n"
        "  - yml_agent\n"
        "  - remote_df_sub\n"
        "modelSettings:\n"
        "  model: gemini-composite-v2\n",
        encoding="utf-8",
    )

    sub_json = tmp_path / "agents" / "sub_agent" / "sub_agent.json"
    sub_json.parent.mkdir(parents=True)
    (sub_json.parent / "instruction.txt").write_text(
        "<role>Sub</role>\n<persona>Calm</persona>\n"
        "<constraints>Today is {{current_date}}.</constraints>\n"
        "<taskflow>Handle</taskflow>\n",
        encoding="utf-8",
    )
    sub_json.write_text(
        json.dumps(
            {
                "displayName": "sub_agent",
                "instruction": "agents/sub_agent/instruction.txt",
                "modelSettings": {
                    "model": "publishers/google/models/gemini-composite-v1"
                },
            }
        ),
        encoding="utf-8",
    )

    yml_agent = tmp_path / "agents" / "yml_agent" / "yml_agent.yml"
    yml_agent.parent.mkdir(parents=True)
    (yml_agent.parent / "instruction.txt").write_text(
        "<role>Yml</role>\n<persona>Clear</persona>\n"
        "<constraints>Today is {{current_date}}.</constraints>\n"
        "<taskflow>Assist</taskflow>\n",
        encoding="utf-8",
    )
    yml_agent.write_text(
        "displayName: yml_agent\n"
        "instruction: agents/yml_agent/instruction.txt\n"
        "modelSettings:\n"
        "  model: models/gemini-composite-v3\n",
        encoding="utf-8",
    )

    remote_df_yaml = (
        tmp_path / "agents" / "remote_df_sub" / "remote_df_sub.yaml"
    )
    remote_df_yaml.parent.mkdir(parents=True)
    remote_df_yaml.write_text(
        "displayName: remote_df_sub\nremoteDialogflowAgent: {}\n",
        encoding="utf-8",
    )

    # Full run_rules (no specific_rules filter) validates JSON/YAML/YML cleanly
    app_json.write_text(
        json.dumps(
            {
                "name": "projects/p/locations/global/apps/voice_app",
                "displayName": "Voice App",
                "rootAgent": "root_agent",
            }
        ),
        encoding="utf-8",
    )
    disc = Discovery(tmp_path, tmp_path / "evals")
    cfg = LintConfig()
    full_ctx = build_context(tmp_path, cfg, disc)
    report = LintReport()
    run_rules(build_registry(), cfg, full_ctx, disc, report)
    assert [r.rule_id for r in report.errors] == ["A019", "A019", "A019"]
    flagged_files = {Path(r.file).name for r in report.errors}
    assert flagged_files == {
        "root_agent.yaml",
        "sub_agent.json",
        "yml_agent.yml",
    }


