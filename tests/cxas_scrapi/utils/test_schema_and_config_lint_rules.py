def test_a004_skips_guided_and_remote_dialogflow_agents(
    tmp_path: Path, context: LintContext
) -> None:
    rule = AgentMissingInstruction()

    for key in ("guidedAgent", "remoteDialogflowAgent"):
        agent_dir = tmp_path / "agents" / f"agent_{key}"
        agent_dir.mkdir(parents=True, exist_ok=True)
        agent_json = agent_dir / f"agent_{key}.json"
        agent_json.write_text(
            json.dumps({"displayName": f"agent_{key}", key: {}})
        )
        results = rule.check(agent_json, agent_json.read_text(), context)
        assert results == []


def test_a005_and_a006_resolve_root_agent_display_name_with_spaces(
    tmp_path: Path, context: LintContext
) -> None:
    app_json = tmp_path / "app.json"
    app_json.write_text(json.dumps({"rootAgent": "Root agent"}))

    agent_dir = tmp_path / "agents" / "Root_agent"
    agent_dir.mkdir(parents=True)
    (agent_dir / "Root_agent.json").write_text(
        json.dumps({"displayName": "Root agent", "tools": ["end_session"]})
    )

    a006 = AppRootAgentValidation()
    assert a006.check(app_json, app_json.read_text(), context) == []

    a005 = RootAgentMissingEndSession()
    assert a005.check(app_json, app_json.read_text(), context) == []


def test_a005_flags_missing_end_session_when_resolved_via_display_name(
    tmp_path: Path, context: LintContext
) -> None:
    app_json = tmp_path / "app.json"
    app_json.write_text(json.dumps({"rootAgent": "Research Assistant"}))

    agent_dir = tmp_path / "agents" / "research_root"
    agent_dir.mkdir(parents=True)
    (agent_dir / "research_root.json").write_text(
        json.dumps({"displayName": "Research Assistant", "tools": []})
    )

    a006 = AppRootAgentValidation()
    assert a006.check(app_json, app_json.read_text(), context) == []

    a005 = RootAgentMissingEndSession()
    results = a005.check(app_json, app_json.read_text(), context)
    assert len(results) == 1
    assert "missing 'end_session'" in results[0].message


