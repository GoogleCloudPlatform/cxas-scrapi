@pytest.fixture
def context(tmp_path: Path) -> LintContext:
    return LintContext(
        project_root=tmp_path, app_dir=tmp_path, evals_dir=tmp_path
    )


def test_v001_variable_declaration_without_description_passes(
    tmp_path: Path, context: LintContext
) -> None:
    registry = build_registry()
    rule = registry.get("V001")

    app_dir = tmp_path / "myapp"
    app_dir.mkdir()
    (app_dir / "app.json").write_text(
        json.dumps(
            {
                "displayName": "MyApp",
                "variableDeclarations": [
                    {
                        "name": "customer_id",
                        "schema": {"type": "STRING"},
                    }
                ],
            }
        )
    )

    with patch("cxas_scrapi.utils.lint_rules.schema.json_format.ParseDict"):
        results = rule.check(app_dir, "", context)
        assert results == []


